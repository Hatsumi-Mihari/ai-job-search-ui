import { ModuleRef } from '@nestjs/core';
import { Injectable, Logger } from '@nestjs/common';

import {
  TestService,
  type VacancyMutationResult,
} from '@/entities/vacances/vac.service.js';
import { StorageFileService } from '@/entities/storage_files/sf.service.js';
import type { VacancyEntity } from '@/entities/vacances/vac.entity.js';
import { Tool } from '@nestjs/mcp';
import z from 'zod';
import {
  type CreateVacancyInput,
  type UpdateVacancyInput,
  toCreateVacancyDto,
  toUpdateVacancyDto,
} from './utils/vac-payload.util.js';

const CONTEXT = 'McpVacWorker';

/**
 * Key points for MCP tools that work with vacancies.
 *
 * `TestService` (`entities/vacances/vac.service.ts`) is the single source of
 * truth; tools resolve it through `ModuleRef` instead of touching the
 * repository, so validation and `@Measure` tracking stay in one place.
 *
 * 1. Addressing: every read/update/delete targets a row by a positive integer
 *    `id`. There is no lookup by company/role/status, so resolve the id first
 *    (`vacancy_list`, then `vacancy_get`). `company`, `status` and `chanel` are
 *    hash-indexed, but the service exposes no filtered query.
 * 2. Create: `date_pub`, `company`, `status`, `role`, `fit_rating`, `source`,
 *    `note` and `chanel` are required. `source_resume_id` /
 *    `source_cover_latter_id` are optional UUIDs. `id` and `date_add` are
 *    generated by the database.
 * 3. Update: partial by design — only the keys present in the payload change;
 *    `undefined` keeps the current value; an empty patch throws
 *    `BadRequestException`; unknown keys are silently dropped (a typo such as
 *    `channel` changes nothing — the column is spelled `chanel`).
 * 4. Field limits: `company` <= 255 chars, `status` <= 100, `chanel` <= 50,
 *    `fit_rating` must be an integer, `role`/`note`/`source` are non-empty
 *    strings, `date_pub` is a Postgres `date` (ISO `YYYY-MM-DD`).
 * 5. Documents: `source_resume_id` / `source_cover_latter_id` are UUIDs of
 *    rows in `storage_files`, not S3 paths. Link them with the attach tools,
 *    or use `vacancy_create_with_empty_documents` to create placeholder files.
 * 6. Delete: by id only and not idempotent — a missing row raises
 *    `NotFoundException`, as does any operation on a missing vacancy.
 * 7. Errors: `BadRequestException` for invalid input, `NotFoundException` for
 *    a missing vacancy. `@nestjs/mcp` turns them into `isError: true` results,
 *    so tool output is returned as plain data instead of being re-wrapped.
 */

/** Shared schema for the primary key of a vacancy. */
const vacancyIdSchema = z
  .number()
  .int()
  .positive()
  .describe('Vacancy id (positive integer)');

/** Fields written on creation; mirrors `CreateVacancyDto`. */
const createVacancySchema = z.object({
  date_pub: z.string().min(1).describe('Publication date (ISO YYYY-MM-DD)'),
  company: z.string().min(1).max(255).describe('Company name'),
  status: z
    .string()
    .min(1)
    .max(100)
    .describe('Application status, e.g. "found", "applied", "interview"'),
  role: z.string().min(1).describe('Role / position title'),
  fit_rating: z.number().int().describe('Fit rating score (integer)'),
  source: z.string().min(1).describe('Source URL or link'),
  note: z.string().min(1).describe('Additional notes'),
  chanel: z
    .string()
    .min(1)
    .max(50)
    .describe('Application channel (column is spelled "chanel")'),
  source_resume_id: z
    .uuid()
    .nullable()
    .optional()
    .describe('UUID of the resume row in storage_files'),
  source_cover_latter_id: z
    .uuid()
    .nullable()
    .optional()
    .describe('UUID of the cover letter row in storage_files'),
});

/** Every column except `id` is optional: `TestService` applies a partial patch. */
const updateVacancySchema = createVacancySchema.partial().extend({
  id: vacancyIdSchema,
});

const createVacancyWithEmptyDocumentsSchema = createVacancySchema.omit({
  source_resume_id: true,
  source_cover_latter_id: true,
});

@Injectable()
export class McpVacWorker {
  constructor(private readonly moduleRef: ModuleRef) {}

  private get vacService(): TestService {
    return this.moduleRef.get(TestService, { strict: false });
  }

  private get storageFileService(): StorageFileService {
    return this.moduleRef.get(StorageFileService, { strict: false });
  }

  // ------------------------------------------------------------------- read

  @Tool({
    name: 'vacancy_list',
    description:
      'Returns every vacancy with all columns. There are no filters: list the rows and filter by company/status/chanel client-side.',
  })
  async vacancyList(): Promise<VacancyEntity[]> {
    Logger.log('vacancy_list', CONTEXT);

    return await this.vacService.findAll();
  }

  @Tool({
    name: 'vacancy_get',
    description:
      'Returns one vacancy by id. Fails with NotFoundException when the row does not exist.',
    inputSchema: z.object({ id: vacancyIdSchema }),
  })
  async vacancyGet({
    id,
  }: {
    id: z.infer<typeof vacancyIdSchema>;
  }): Promise<VacancyEntity> {
    Logger.log(`vacancy_get id=${id}`, CONTEXT);

    return await this.vacService.findOneById(id);
  }

  // ----------------------------------------------------------------- create

  @Tool({
    name: 'vacancy_create',
    description:
      'Creates a vacancy. Required: date_pub, company, status, role, fit_rating, source, note, chanel. Document ids are optional UUIDs from storage_files.',
    inputSchema: createVacancySchema,
  })
  async vacancyCreate(
    input: CreateVacancyInput,
  ): Promise<VacancyMutationResult> {
    Logger.log(`vacancy_create company=${input.company}`, CONTEXT);

    return await this.vacService.createVac(toCreateVacancyDto(input));
  }

  @Tool({
    name: 'vacancy_create_with_empty_documents',
    description:
      'Creates a vacancy together with two empty placeholder storage_files rows and links them as resume and cover letter. If vacancy creation fails, the placeholder files remain orphaned.',
    inputSchema: createVacancyWithEmptyDocumentsSchema,
  })
  async vacancyCreateWithEmptyDocuments(
    input: Omit<
      CreateVacancyInput,
      'source_resume_id' | 'source_cover_latter_id'
    >,
  ): Promise<
    VacancyMutationResult & {
      documents: { resume_id: string | null; cover_letter_id: string | null };
    }
  > {
    const resume = await this.storageFileService.createStorageFileEmpty('null');
    const coverLetter =
      await this.storageFileService.createStorageFileEmpty('null');

    Logger.log(
      `vacancy_create_with_empty_documents resume=${resume.id} coverLetter=${coverLetter.id}`,
      CONTEXT,
    );

    const result = await this.vacService.createVac(
      toCreateVacancyDto({
        ...input,
        source_resume_id: resume.id ?? null,
        source_cover_latter_id: coverLetter.id ?? null,
      }),
    );

    return {
      ...result,
      documents: {
        resume_id: resume.id ?? null,
        cover_letter_id: coverLetter.id ?? null,
      },
    };
  }

  // ----------------------------------------------------------------- update

  @Tool({
    name: 'vacancy_update',
    description:
      'Partially updates a vacancy: only the provided fields change. id and date_add are database-managed and cannot be edited. The column is spelled "chanel".',
    inputSchema: updateVacancySchema,
  })
  async vacancyUpdate(
    input: z.infer<typeof updateVacancySchema>,
  ): Promise<VacancyMutationResult> {
    const { id, ...patch } = input;

    Logger.log(`vacancy_update id=${id}`, CONTEXT);

    return await this.vacService.updateVac(
      id,
      toUpdateVacancyDto(patch as UpdateVacancyInput),
    );
  }

  @Tool({
    name: 'vacancy_attach_resume',
    description:
      'Links an existing storage_files row (UUID) to the vacancy as its resume.',
    inputSchema: z.object({
      id: vacancyIdSchema,
      storage_file_id: z
        .uuid()
        .describe('UUID of an existing row in storage_files'),
    }),
  })
  async vacancyAttachResume({
    id,
    storage_file_id,
  }: {
    id: z.infer<typeof vacancyIdSchema>;
    storage_file_id: string;
  }): Promise<VacancyMutationResult> {
    Logger.log(
      `vacancy_attach_resume id=${id} file=${storage_file_id}`,
      CONTEXT,
    );

    return await this.vacService.updateVacResumePath(id, storage_file_id);
  }

  @Tool({
    name: 'vacancy_attach_cover_letter',
    description:
      'Links an existing storage_files row (UUID) to the vacancy as its cover letter.',
    inputSchema: z.object({
      id: vacancyIdSchema,
      storage_file_id: z
        .uuid()
        .describe('UUID of an existing row in storage_files'),
    }),
  })
  async vacancyAttachCoverLetter({
    id,
    storage_file_id,
  }: {
    id: z.infer<typeof vacancyIdSchema>;
    storage_file_id: string;
  }): Promise<VacancyMutationResult> {
    Logger.log(
      `vacancy_attach_cover_letter id=${id} file=${storage_file_id}`,
      CONTEXT,
    );

    return await this.vacService.updateVacCoverLetterPath(id, storage_file_id);
  }

  // ----------------------------------------------------------------- delete

  @Tool({
    name: 'vacancy_delete',
    description:
      'Deletes a vacancy by id. Not idempotent: deleting a missing row fails with NotFoundException.',
    inputSchema: z.object({ id: vacancyIdSchema }),
  })
  async vacancyDelete({
    id,
  }: {
    id: z.infer<typeof vacancyIdSchema>;
  }): Promise<VacancyMutationResult> {
    Logger.log(`vacancy_delete id=${id}`, CONTEXT);

    return await this.vacService.deleteVacById(id);
  }
}
