import { ModuleRef } from '@nestjs/core';
import { BadRequestException, Injectable, Logger } from '@nestjs/common';
import { spawn } from 'child_process';

import {
  TestService,
  UpdateVacancyDto,
  VacancyMutationResult,
} from '@/entities/vacances/vac.service.js';
import { CreateVacancyDto } from '@/entities/vacances/dto/create-vac.dto.js';
import { VacancyEntity } from '@/entities/vacances/vac.entity.js';
import { OpenCodeService } from '@/common/services/opencode/opencode.service.js';
import { StorageFileService } from '@/entities/storage_files/sf.service.js';
import {
  asInteger,
  asNonEmptyString,
  asPositiveInteger,
} from './utils/vac-payload.util.js';

/**
 * Columns a worker is allowed to write after creation. Mirrors
 * `TestService.EDITABLE_FIELDS`; `id` and `date_add` are database-managed.
 */
export type VacancyEditableField =
  | 'date_pub'
  | 'company'
  | 'status'
  | 'role'
  | 'fit_rating'
  | 'source'
  | 'note'
  | 'chanel'
  | 'source_cover_latter_id'
  | 'source_resume_id';

/**
 * Key points for MCP workers that work with vacancies.
 *
 * The single source of truth is `TestService` (`entities/vacances/vac.service.ts`).
 * Workers must call it through `ModuleRef` instead of touching repositories or
 * writing SQL, so validation and `@Measure` tracking stay in one place.
 *
 * 1. Addressing: every read/update/delete targets a row by a positive integer
 *    `id`. No lookup by company/role/status exists, so resolve the id first.
 * 2. Create: `CreateVacancyDto` requires `date_pub`, `company`, `status`,
 *    `role`, `fit_rating`, `source`, `note`, `chanel`; both document ids are
 *    optional (`null` allowed). `date_add` and `id` are generated by the DB.
 * 3. Update: partial by design — only the keys present in the payload change.
 *    `undefined` keeps the current value, an empty patch throws
 *    `BadRequestException`, and unknown keys are silently dropped (a typo like
 *    `channel` will not update anything — the column is spelled `chanel`).
 * 4. Field rules: `company` <= 255 chars, `status` <= 100, `chanel` <= 50,
 *    `fit_rating` must be an integer, `role`/`note`/`source` non-empty strings.
 *    `date_pub` is a Postgres `date`; send an ISO `YYYY-MM-DD` string.
 * 5. Documents: `source_resume_id` / `source_cover_latter_id` are UUIDs of rows
 *    in `storage_files`, not S3 paths. Use `attachResume` / `attachCoverLetter`
 *    with an id returned by `StorageFileService`; the DTO caps the text column
 *    at 500 chars, while the FK requires the referenced file to exist.
 * 6. Delete: by id only and not idempotent — deleting a missing row (or any
 *    operation on a missing row) throws `NotFoundException`.
 * 7. Errors: `BadRequestException` for invalid input, `NotFoundException` for a
 *    missing vacancy. Workers should surface `success`/`message`/`id` as-is.
 */
@Injectable()
export class McpVacWorker {
  constructor(
    private readonly moduleRef: ModuleRef
  ) {}

  private get vacService(): TestService {
    return this.moduleRef.get(TestService, { strict: false });
  }

  private get storageFileService(): StorageFileService {
    return this.moduleRef.get(StorageFileService, { strict: false });
  }

  private get openCodeService(): OpenCodeService {
    return this.moduleRef.get(OpenCodeService, { strict: false });
  }

  // ------------------------------------------------------------------ read

  /** Returns every vacancy. Cheap because the table is small; no filters exist. */
  async listVacancies(): Promise<VacancyEntity[]> {
    Logger.log('listVacancies', 'McpVacWorker');
    return await this.vacService.findAll();
  }

  /** Returns one vacancy by id; throws `NotFoundException` when it is missing. */
  async getVacancy(id: unknown): Promise<VacancyEntity> {
    const vacancyId = asPositiveInteger(id);
    Logger.log(`getVacancy id=${vacancyId}`, 'McpVacWorker');
    return await this.vacService.findOneById(vacancyId);
  }

  // ---------------------------------------------------------------- create

  /**
   * Creates a vacancy. Requires the full `CreateVacancyDto`; optional document
   * ids must already exist in `storage_files` (see `attachResume`).
   */
  async createVacancy(vacDTO: CreateVacancyDto): Promise<VacancyMutationResult> {
    Logger.log(`createVacancy company=${vacDTO?.company}`, 'McpVacWorker');
    return await this.vacService.createVac(vacDTO);
  }

  /**
   * Convenience flow used by automation: creates two empty storage files, then
   * creates the vacancy already linked to them.
   *
   * Key point: if vacancy creation fails, the empty files stay orphaned —
   * delete them with `StorageFileService.deleteStorageFilesByName` if needed.
   */
  async createVacancyWithEmptyDocuments(
    vacDTO: Omit<CreateVacancyDto, 'source_cover_latter_id' | 'source_resume_id'>,
  ): Promise<VacancyMutationResult> {
    const fileEmptyCV = await this.storageFileService.createStorageFileEmpty('null');
    const fileEmptyCL = await this.storageFileService.createStorageFileEmpty('null');

    Logger.log(
      `createVacancyWithEmptyDocuments resume=${fileEmptyCV.id} coverLetter=${fileEmptyCL.id}`,
      'McpVacWorker',
    );

    return await this.vacService.createVac({
      ...vacDTO,
      source_resume_id: fileEmptyCV.id ?? null,
      source_cover_latter_id: fileEmptyCL.id ?? null,
    });
  }

  // ---------------------------------------------------------------- update

  /**
   * Partial update. Only keys present in `patch` are written; `id` and
   * `date_add` cannot be changed even if they are present.
   */
  async updateVacancy(id: unknown, patch: UpdateVacancyDto): Promise<VacancyMutationResult> {
    const vacancyId = asPositiveInteger(id);
    Logger.log(`updateVacancy id=${vacancyId}`, 'McpVacWorker');
    return await this.vacService.updateVac(vacancyId, patch);
  }

  /**
   * Updates exactly one column and keeps the per-field validation of
   * `TestService` (max lengths, integer `fit_rating`, non-empty strings).
   */
  async updateVacancyField(
    id: unknown,
    field: VacancyEditableField,
    value: unknown,
  ): Promise<VacancyMutationResult> {
    const vacancyId = asPositiveInteger(id);

    Logger.log(`updateVacancyField id=${vacancyId} field=${field}`, 'McpVacWorker');

    switch (field) {
      case 'date_pub':
        return await this.vacService.updateVacDatePub(
          vacancyId,
          asNonEmptyString(value, field),
        );
      case 'company':
        return await this.vacService.updateVacCompany(
          vacancyId,
          asNonEmptyString(value, field),
        );
      case 'status':
        return await this.vacService.updateVacStatus(
          vacancyId,
          asNonEmptyString(value, field),
        );
      case 'role':
        return await this.vacService.updateVacRole(
          vacancyId,
          asNonEmptyString(value, field),
        );
      case 'fit_rating':
        return await this.vacService.updateVacFitRating(
          vacancyId,
          asInteger(value, field),
        );
      case 'source':
        return await this.vacService.updateVacSource(
          vacancyId,
          asNonEmptyString(value, field),
        );
      case 'note':
        return await this.vacService.updateVacNote(
          vacancyId,
          asNonEmptyString(value, field),
        );
      case 'chanel':
        return await this.vacService.updateVacChannel(
          vacancyId,
          asNonEmptyString(value, field),
        );
      case 'source_cover_latter_id':
        return await this.vacService.updateVacCoverLetterPath(
          vacancyId,
          asNonEmptyString(value, field),
        );
      case 'source_resume_id':
        return await this.vacService.updateVacResumePath(
          vacancyId,
          asNonEmptyString(value, field),
        );
      default:
        throw new BadRequestException(
          `Field ${String(field)} cannot be updated; allowed fields: ${McpVacWorker.editableFields().join(', ')}`,
        );
    }
  }

  /** Links an existing `storage_files` row to the vacancy as its resume. */
  async attachResume(id: unknown, fileId: unknown): Promise<VacancyMutationResult> {
    const vacancyId = asPositiveInteger(id);
    const resumeId = asNonEmptyString(fileId, 'source_resume_id');

    Logger.log(`attachResume id=${vacancyId} file=${resumeId}`, 'McpVacWorker');
    return await this.vacService.updateVacResumePath(vacancyId, resumeId);
  }

  /** Links an existing `storage_files` row to the vacancy as its cover letter. */
  async attachCoverLetter(id: unknown, fileId: unknown): Promise<VacancyMutationResult> {
    const vacancyId = asPositiveInteger(id);
    const coverLetterId = asNonEmptyString(fileId, 'source_cover_latter_id');

    Logger.log(`attachCoverLetter id=${vacancyId} file=${coverLetterId}`, 'McpVacWorker');
    return await this.vacService.updateVacCoverLetterPath(vacancyId, coverLetterId);
  }

  // ---------------------------------------------------------------- delete

  /** Deletes a vacancy by id; a second call throws `NotFoundException`. */
  async deleteVacancy(id: unknown): Promise<VacancyMutationResult> {
    const vacancyId = asPositiveInteger(id);
    Logger.log(`deleteVacancy id=${vacancyId}`, 'McpVacWorker');
    return await this.vacService.deleteVacById(vacancyId);
  }

  // --------------------------------------------------------------- helpers

  /** Fields accepted by `updateVacancyField`, kept in sync with the service. */
  private static editableFields(): ReadonlyArray<VacancyEditableField> {
    return [
      'date_pub',
      'company',
      'status',
      'role',
      'fit_rating',
      'source',
      'note',
      'chanel',
      'source_cover_latter_id',
      'source_resume_id',
    ];
  }

  async test(taskId: string) {
    
  }
}
